"""Regenerate versioned display covers; requires Pillow. Originals are never overwritten."""
from pathlib import Path
from PIL import Image, ImageOps
import hashlib, io, json

root = Path(__file__).resolve().parent.parent
mapping = {}
for story in json.loads((root / 'src/studio/storyCatalog.json').read_text('utf-8')):
    source = story['cover']
    image = ImageOps.exif_transpose(Image.open(root / ('public' + source))).convert('RGB')
    variants = {}
    for kind, width, quality in [('thumbnail', 320, 80), ('display', 800, 84)]:
        resized = image.copy()
        resized.thumbnail((width, round(width * image.height / image.width)), Image.Resampling.LANCZOS)
        buffer = io.BytesIO()
        resized.save(buffer, format='WEBP', quality=quality, method=6)
        data = buffer.getvalue()
        budget = 240000 if kind == 'display' else 60000
        while len(data) > budget:
            if quality > 72:
                quality -= 4
            else:
                resized = resized.resize((round(resized.width * .9), round(resized.height * .9)), Image.Resampling.LANCZOS)
            buffer = io.BytesIO()
            resized.save(buffer, format='WEBP', quality=quality, method=6)
            data = buffer.getvalue()
        digest = hashlib.sha256(data).hexdigest()[:12]
        path = f'/assets/cover-{story["id"]}-{kind}-{digest}.webp'
        target = root / ('public' + path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        variants[kind] = path
    mapping[source] = variants
(root / 'src/cover-images.ts').write_text(
    '// Generated by scripts/build-cover-images.py. Original paths remain the source of truth.\n'
    + 'const covers: Record<string, {thumbnail: string; display: string}> = '
    + json.dumps(mapping, ensure_ascii=False, indent=2)
    + ';\n\nexport function coverImage(source: string, size: "thumbnail" | "display" = "display"): string {\n'
    + '  return covers[source]?.[size] ?? source;\n}\n', encoding='utf-8')

(root / 'shared/task-cover-images.json').write_text(json.dumps({source: variants['thumbnail'] for source, variants in mapping.items()}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
