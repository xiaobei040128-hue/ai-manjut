import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir,mkdtemp} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {createStore} from '../server/store.mjs';
import {createAdminAuth} from '../server/auth.mjs';
import {createCreatorAuth} from '../server/creator-auth.mjs';
import {createFinance} from '../server/finance.mjs';
import {createOperatorScope} from '../server/operators.mjs';
import {createStageEnrollments} from '../server/stage-enrollments.mjs';
const quote=t=>({amount:t.deposit,commission:t.commission,rateBps:t.commission_rate_bps});
test('production stages freeze server quotes and settle once, independent of later policy changes',async()=>{
 await mkdir(resolve('work'),{recursive:true});const dir=await mkdtemp(resolve('work/stage-finance-')),s=createStore(join(dir,'workspace.sqlite'));
 try{
  assert.equal(s.summary().wallet.available,0);assert.equal(s.allTasks().length,0);
  const admin=createAdminAuth(s,4986);admin.setup({username:'stage-admin',password:'StageFinanceQA123!'});
  const auth=createCreatorAuth(s,4986),finance=createFinance(s,dir),scope=createOperatorScope(s),enroll=createStageEnrollments(s,scope);
  const inv=auth.createInvite('stage-admin',{},'super'),req={headers:{},socket:{remoteAddress:'stage-qa'}};
  const user=(await auth.register(req,{email:'stage-qa@example.invalid',password:'StageFinanceQA123!',inviteCode:inv.code})).user;
  finance.adjust('stage-admin',user.id,{direction:'credit',amount:'1000',note:'Isolated QA funding',operationKey:'stage-test-funding-0001'});
  for(const invalid of ['-1','100.01','1e2','0.001',null,''])assert.throws(()=>s.setCommissionRate(invalid));
  s.setCommissionRate('5');
  const tasks=[1,2,3].map(stage=>s.createTask({title:'阶段任务 '+stage,description:'发布一条合规作品',platform:'TikTok',language:'中文',genre:'剧情',deposit:'100',commission:'999',posts:1,episodes:1,slots:10,cover:'/art/hero-v2.webp',stage}));
  assert.equal(tasks[0].commission,500);
  assert.throws(()=>s.createTask({...tasks[0],deposit:'100.001'}));
  const poor=(await auth.register(req,{email:'stage-unfunded@example.invalid',password:'StageFinanceQA123!',inviteCode:inv.code})).user;
  assert.throws(()=>s.asUser(poor.id,()=>s.claim(tasks[0].id,quote(tasks[0]))),e=>e.status===409);
  assert.equal(s.db.prepare('SELECT COUNT(*) n FROM assignments WHERE owner_id=?').get(poor.id).n,0);
  assert.equal(s.asUser(poor.id,()=>s.summary()).wallet.available,0);
  const as=fn=>s.asUser(user.id,fn);
  assert.throws(()=>as(()=>s.claim(tasks[1].id,quote(tasks[1]))),e=>e.status===403);
  assert.throws(()=>as(()=>s.claim(tasks[0].id,{amount:1,commission:500,rateBps:500})),e=>e.status===409);
  let a=as(()=>s.claim(tasks[0].id,quote(tasks[0])));assert.equal(as(()=>s.claim(tasks[0].id,quote(tasks[0]))).id,a.id);
  assert.equal(as(()=>s.summary()).wallet.available,90000);assert.equal(as(()=>s.summary()).wallet.held,10000);
  s.setCommissionRate('10');assert.equal(s.getTask(tasks[0].id).commission,1000);assert.equal(as(()=>s.assignment(a.id)).task.commission,500);
  const u=as(()=>s.addUpload(a.id,{name:'proof.png',mime:'image/png',size:24,path:'/uploads/11111111-1111-1111-1111-111111111111.png'}));
  as(()=>s.submit(a.id,{links:['https://example.invalid/proof'],uploadIds:[u.id]}));
  s.review(a.id,{decision:'approve'});s.review(a.id,{decision:'approve'});
  assert.equal(as(()=>s.summary()).wallet.available,100500);assert.equal(as(()=>s.summary()).wallet.held,0);assert.equal(as(()=>s.summary()).wallet.earned,500);
  assert.equal(s.db.prepare("SELECT COUNT(*) n FROM ledger WHERE operation_key=?").get('reward:'+a.id).n,1);
  assert.equal(enroll.status(user.id).eligible,false);
  const second=s.getTask(tasks[1].id);a=as(()=>s.claim(second.id,quote(second)));
  const u2=as(()=>s.addUpload(a.id,{name:'proof.png',mime:'image/png',size:24,path:'/uploads/22222222-2222-2222-2222-222222222222.png'}));as(()=>s.submit(a.id,{links:['https://example.invalid/proof2'],uploadIds:[u2.id]}));s.review(a.id,{decision:'approve'});
  assert.equal(enroll.status(user.id).eligible,true);
  const third=s.getTask(tasks[2].id);assert.throws(()=>as(()=>s.claim(third.id,quote(third))),e=>e.status===403);
  const application=enroll.apply(user.id);enroll.review({id:'super',role:'super',username:'stage-admin'},application.enrollment.id,{decision:'approve'});
  a=as(()=>s.claim(third.id,quote(third)));s.setCommissionRate('20');as(()=>s.cancel(a.id));as(()=>s.cancel(a.id));
  assert.equal(as(()=>s.summary()).wallet.available,101500);assert.equal(as(()=>s.summary()).wallet.held,0);
  assert.equal(as(()=>s.assignment(a.id)).task.commission,1000);
  assert.throws(()=>as(()=>s.claim(third.id,quote(third))),e=>e.status===409);
  assert.equal(s.db.prepare("SELECT COUNT(*) n FROM ledger WHERE operation_key=?").get('cancel:'+a.id).n,1);
 }finally{s.close();}
});
